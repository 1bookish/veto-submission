// node tools/gen-synthetic-phishing.js [--n 30000] [--out data/synthetic/phishing-synthetic.tsv]
// Generates SYNTHETIC phishing URLs for training experiments. Every row is labelled synthetic in its source column.
// These are not real phishing sites and must never be reported as real data or as accuracy on real data.
// Seeded: the same command always gives the same file. Lure words and families differ from the attack-test transforms.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BRANDS } from '../data/brands.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const arg = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const N = Number(arg('--n', 30000));
const OUT = arg('--out', path.join(ROOT, 'data', 'synthetic', 'phishing-synthetic.tsv'));

let seed = 20261124;
const rnd = () => { seed = (Math.imul(seed, 1103515245) + 12345) >>> 0; return seed / 4294967296; };
const pick = a => a[Math.floor(rnd() * a.length)];
const alnum = n => Array.from({ length: n }, () => 'abcdefghjkmnpqrstuvwxyz23456789'[Math.floor(rnd() * 32)]).join('');
const syl = ['zor', 'kal', 'mer', 'vin', 'bel', 'qua', 'rin', 'dax', 'fen', 'lom', 'pex', 'tun', 'gry', 'hok'];
const word = () => pick(syl) + pick(syl);
const TLDS = ['xyz', 'top', 'icu', 'site', 'online', 'click', 'shop', 'buzz', 'info', 'live', 'fun'];
const LURES = ['account-check', 'id-renew', 'pay-due', 'profile-update', 'unlock-access', 'reward-claim', 'card-review', 'mobile-pin', 'tax-refund', 'parcel-hold'];
const BUCKETS = ['s3.amazonaws.com', 'storage.googleapis.com', 'blob.core.windows.net'];
const brands = BRANDS.slice(0, BRANDS.indexOf('paypal')).filter(t => t.length >= 5);

const families = [
  ['uae_brand_lure', 0.20, () => `https://${pick(brands)}-${pick(LURES)}.${pick(TLDS)}/${alnum(6)}`],
  ['random_name_lure_path', 0.20, () => `https://${word()}${alnum(4)}.${pick(TLDS)}/${pick(LURES)}/${alnum(8)}.html`],
  ['public_bucket_file', 0.10, () => `https://${alnum(10)}.${pick(BUCKETS)}/${pick(LURES)}/${alnum(6)}.html`],
  ['ip_host_lure', 0.05, () => `http://${1 + Math.floor(rnd() * 223)}.${Math.floor(rnd() * 255)}.${Math.floor(rnd() * 255)}.${Math.floor(rnd() * 255)}/${pick(LURES)}/${alnum(6)}`],
  ['random_name_random_path', 0.20, () => `https://${word()}-${word()}.${pick(TLDS)}/${alnum(12)}`],
  ['brand_typo', 0.15, () => `https://${pick(brands)}${alnum(3)}.${pick(TLDS)}/${pick(LURES)}`],
  ['lure_subdomain', 0.10, () => `https://${pick(LURES)}.${word()}${alnum(3)}.${pick(TLDS)}/`],
];

const rows = [];
const counts = {};
for (const [name, share, make] of families) {
  const k = Math.round(N * share);
  counts[name] = k;
  for (let i = 0; i < k; i++) rows.push({ family: name, url: make() });
}
// shuffle with the same seeded generator, so the families are mixed
for (let i = rows.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [rows[i], rows[j]] = [rows[j], rows[i]]; }

fs.mkdirSync(path.dirname(OUT), { recursive: true });
const header = 'label\tsource\tnew_domain\turl\n';
fs.writeFileSync(OUT, header + rows.map(r => `1\tsynthetic_phishing\t0\t${r.url}`).join('\n') + '\n');
fs.writeFileSync(path.join(path.dirname(OUT), 'README.md'),
  '# Synthetic phishing URLs (labelled SYNTHETIC)\n\n' +
  'Generated by tools/gen-synthetic-phishing.js with seed 20261124. Not real phishing sites. Used only as training input for a candidate model,\n' +
  'and it is never counted as accuracy on real data. Families and counts: ' + JSON.stringify(counts) + '.\n');
console.log(JSON.stringify({ rows: rows.length, families: counts, out: OUT }, null, 2));
