// Build data/hosting-providers.js: popular registrable domains that hand out subdomains to anyone (free site
// builders, web hosts, temporary preview domains). Evidence: many DIFFERENT phishing hosts under the same registrable
// domain in the dated OpenPhish history, counted ONLY before the cut-off date, so the validation and test windows
// never leak into the list. A subdomain on such a domain gets no popularity discount in the judge.
// Usage: node tools/hosting-providers.js --data ../data_raw/urlv2 [--before 2026-10-04] [--min-hosts 3] [--max-rank 100000]
import fs from 'node:fs';
import path from 'node:path';
import { splitDomain } from '../engine/url.js';
import { parseUrl, trancoRank } from '../engine/urlml2.js';
import { officialFor } from '../engine/url.js';

const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const data = arg('--data', '../data_raw/urlv2');
const before = arg('--before', '2026-10-04');
const minHosts = Number(arg('--min-hosts', 3));
const maxRank = Number(arg('--max-rank', 100000));
const hosts = new Map(); // registrable -> Set(host)
for (const line of fs.readFileSync(path.join(data, 'openphish_history.tsv'), 'utf8').split('\n')) {
  const [day, url] = line.split('\t');
  if (!url || !(day < before)) continue;
  const u = parseUrl(url); if (!u) continue;
  const host = u.hostname.toLowerCase().replace(/^www\d?\./, '');
  const reg = splitDomain(host).registrable;
  if (!reg || host === reg) continue;
  if (!hosts.has(reg)) hosts.set(reg, new Set());
  hosts.get(reg).add(host);
}
const list = [...hosts].map(([reg, s]) => [reg, s.size, trancoRank(reg)])
  .filter(([reg, n, rank]) => n >= minHosts && rank && rank <= maxRank && !officialFor(reg))
  .sort((a, b) => b[1] - a[1]);
const out = `// Generated by tools/hosting-providers.js on ${new Date().toISOString().slice(0, 10)} from OpenPhish history before ${before}\n` +
  `// (min ${minHosts} distinct phishing hosts, Tranco rank <= ${maxRank}). Do not edit by hand.\n` +
  `export default ${JSON.stringify(Object.fromEntries(list.map(([reg, n, rank]) => [reg, { phishing_hosts: n, rank }])), null, 1)};\n`;
fs.writeFileSync(new URL('../data/hosting-providers.js', import.meta.url), out);
console.log(`${list.length} hosting providers written (top: ${list.slice(0, 12).map(x => x[0] + ':' + x[1]).join(', ')})`);
