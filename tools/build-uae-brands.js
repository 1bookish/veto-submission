// node tools/build-uae-brands.js
// Builds data/uae-brands.js: the UAE brand watchlist that the look-alike rules (engine/url.js) protect besides the
// rulebook's institutions. Two sources, both written down here:
//   1. a rule: every .ae registrable domain in the Tranco top 100,000 whose name has 4 letters or more, that is not
//      already a rulebook institution, and is not a generic word (cities, common Arabic words, "server", ...);
//   2. a short list of UAE consumer brands that scams impersonate and that are not .ae top sites or rulebook entries.
// These domains are NOT added to the official allowlist: they are look-alike targets only. A brand whose name is also
// an everyday word is "weak": it counts only next to words like "pay" or "login", or with the URL model, never alone.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitDomain, officialFor } from '../engine/url.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TRANCO = path.join(ROOT, '..', 'data_raw', 'tranco', 'top-1m.csv');
const OUT = path.join(ROOT, 'data', 'uae-brands.js');

// generic words and cities: never a brand token (a common word in a domain says nothing about who runs it)
const GENERIC = new Set(['abudhabi', 'dubai', 'sharjah', 'ajman', 'emirates', 'server', 'next', 'alkhaleej', 'albayan', 'sabaya', 'alshamil', 'watchwrestling', 'urbi']);
const WEAK = new Set(['zoho', 'tabby', 'tamara']);
const NAMES = {
  etisalatdomains: ['Etisalat Domains', 'نطاقات اتصالات'], thenational: ['The National', 'ذا ناشيونال'], visitabudhabi: ['Visit Abu Dhabi', 'زوروا أبوظبي'],
  propertyfinder: ['Property Finder', 'بروبرتي فايندر'], trendyol: ['Trendyol', 'ترينديول'], gettyimages: ['Getty Images', 'غيتي إيمجز'],
  desertcart: ['desertcart', 'ديزرت كارت'], tasjeel: ['Tasjeel', 'تسجيل'], aedns: ['.ae domain registry', 'سجل نطاقات .ae'], adnoc: ['ADNOC', 'أدنوك'],
  skyscanner: ['Skyscanner', 'سكاي سكانر'], ounass: ['Ounass', 'أُناس'], duhosting: ['du Hosting', 'استضافة دو'], dubailand: ['Dubai Land Department', 'دائرة الأراضي والأملاك في دبي'],
  gulftoday: ['Gulf Today', 'جلف توداي'], burjkhalifa: ['Burj Khalifa', 'برج خليفة'], zoho: ['Zoho', 'زوهو'], adnocnet: ['ADNOC', 'أدنوك'], astratech: ['Astra Tech', 'أسترا تك'],
  dubaiairports: ['Dubai Airports', 'مطارات دبي'], theuaelottery: ['The UAE Lottery', 'اليانصيب الإماراتي'], eclaimlink: ['eClaimLink', 'إي كليم لينك'], '2gis': ['2GIS', '2GIS'],
  blueirissoft: ['Blue Iris Soft', 'بلو آيرس سوفت'], mofa: ['Ministry of Foreign Affairs', 'وزارة الخارجية'],
};
const CURATED = [
  { id: 'emaar', name: ['Emaar', 'إعمار'], domains: ['emaar.com'] },
  { id: 'dubizzle', name: ['dubizzle', 'دوبيزل'], domains: ['dubizzle.com'] },
  { id: 'bayut', name: ['Bayut', 'بيوت'], domains: ['bayut.com'] },
  { id: 'addc', name: ['Abu Dhabi Distribution Company', 'شركة أبوظبي للتوزيع'], domains: ['addc.ae'] },
  { id: 'tabby', name: ['Tabby', 'تابي'], domains: ['tabby.ai'] },
  { id: 'tamara', name: ['Tamara', 'تمارا'], domains: ['tamara.co'] },
  { id: 'payit', name: ['payit', 'باي إت'], domains: ['payit.ae'] },
  { id: 'botim', name: ['BOTIM', 'بوتيم'], domains: ['botim.me'] },
  { id: 'theuaelottery', name: ['The UAE Lottery', 'اليانصيب الإماراتي'], domains: ['theuaelottery.ae'], tokens: ['uaelottery'] },
];

const brands = new Map();
const rows = fs.readFileSync(TRANCO, 'utf8').split('\n').slice(0, 100000);
for (const line of rows) {
  const dom = (line.split(',')[1] || '').trim().toLowerCase();
  if (!dom) continue;
  const reg = splitDomain(dom).registrable;
  if (!reg) continue;
  const parts = reg.split('.');
  const tld = parts.slice(1).join('.');
  if (!(tld === 'ae' || tld.endsWith('.ae'))) continue;
  const sld = parts[0];
  if (sld.length < 4 || GENERIC.has(sld) || officialFor(reg)) continue;
  if (!brands.has(sld)) {
    const [en, ar] = NAMES[sld] || [reg, reg];
    brands.set(sld, { id: sld, name: { en, ar }, domains: [reg], tokens: [], weak: WEAK.has(sld), source: 'tranco_ae_top100k' });
  } else brands.get(sld).domains.push(reg);
}
for (const c of CURATED) {
  const ex = brands.get(c.id);
  if (ex) { for (const t of c.tokens || []) if (!ex.tokens.includes(t)) ex.tokens.push(t); continue; }
  brands.set(c.id, { id: c.id, name: { en: c.name[0], ar: c.name[1] }, domains: c.domains, tokens: c.tokens || [], weak: WEAK.has(c.id), source: 'curated' });
}
const list = [...brands.values()].sort((a, b) => a.id.localeCompare(b.id));
fs.writeFileSync(OUT, `// Generated by tools/build-uae-brands.js on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// UAE brand watchlist: look-alike targets beside the rulebook's institutions (not an allowlist). Sources: every .ae
// domain in the Tranco top 100,000 with a name of 4+ letters that is not generic or already in the rulebook, and a
// short curated list of UAE consumer brands. "weak" names are everyday words: they count only with other evidence.
export const UAE_BRANDS = ${JSON.stringify(list, null, 1)};
`);
console.log(`data/uae-brands.js: ${list.length} brands (${list.filter(b => b.source === 'curated').length} curated, ${list.filter(b => b.weak).length} weak)`);
console.log(list.map(b => b.domains[0] + (b.weak ? ' (weak)' : '')).join(', '));
