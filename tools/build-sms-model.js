// node tools/build-sms-model.js
// Trains the on-device SMS model on the dev half only, with the same split, features and threshold procedure as
// tools/sms-local.js, and writes engine/smsmodel-data.js. Then it checks that the shipped scorer (engine/smsmodel.js)
// gives the same dev threshold and the same test-half counts as data/sms-local-report.json. Any difference is an error.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { smsTokens } from '../engine/smstokens.js';

if (!process.argv.includes('--naive-bayes')) {
  console.error('superseded: the shipped SMS model now comes from tools/sms-cv.js --ship (logistic regression, nested cross-validation). Pass --naive-bayes to rebuild the old model anyway; it overwrites engine/smsmodel-data.js.');
  process.exit(1);
}
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CSV = path.join(ROOT, '..', 'data_raw', 'smishx', 'dataset.csv');
const REPORT = path.join(ROOT, 'data', 'sms-local-report.json');
const OUT = path.join(ROOT, 'engine', 'smsmodel-data.js');
const TARGET_FA = 0.02;
const ALPHA = 1;

function parseCsv(text) {
  const rows = []; let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else q = false; }
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows;
}
function rng(seed) {
  let s = seed >>> 0;
  return () => { s = (s + 0x6D2B79F5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
function shuffle(arr, r) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

// data and split: the same code and seed as tools/sms-local.js
const rows = parseCsv(fs.readFileSync(CSV, 'utf8'));
const header = rows[0];
const iSMS = header.indexOf('SMS'), iLabel = header.indexOf('label');
const all = rows.slice(1).map((r, idx) => ({ idx, text: r[iSMS], raw: (r[iLabel] || '').trim().toLowerCase() }))
  .map(x => ({ ...x, label: x.raw === 'smishing' ? 'phishing' : x.raw }))
  .filter(x => (x.label === 'phishing' || x.label === 'legitimate') && x.text);
const r = rng(20261125);
const pos = shuffle(all.filter(x => x.label === 'phishing'), r);
const neg = shuffle(all.filter(x => x.label === 'legitimate'), r);
const half = a => Math.floor(a.length / 2);
const devRaw = [...pos.slice(0, half(pos)).map(x => ({ ...x, y: 1 })), ...neg.slice(0, half(neg)).map(x => ({ ...x, y: 0 }))];
const testRaw = [...pos.slice(half(pos)).map(x => ({ ...x, y: 1 })), ...neg.slice(half(neg)).map(x => ({ ...x, y: 0 }))];
const dev = devRaw.map(x => ({ tok: smsTokens(x.text), y: x.y }));

// train on dev only (multinomial Naive Bayes, Laplace alpha 1)
const cnt = [new Map(), new Map()], total = [0, 0], n = [0, 0];
for (const d of dev) {
  n[d.y]++;
  for (const w of d.tok) { cnt[d.y].set(w, (cnt[d.y].get(w) || 0) + 1); total[d.y]++; }
}
const vocab = new Set([...cnt[0].keys(), ...cnt[1].keys()]);
const V = vocab.size;
const prior = Math.log(n[1] / n[0]);
const w = {};
for (const t of vocab) {
  w[t] = Math.log(((cnt[1].get(t) || 0) + ALPHA) / (total[1] + ALPHA * V)) - Math.log(((cnt[0].get(t) || 0) + ALPHA) / (total[0] + ALPHA * V));
}
const devScore = tok => { let s = prior; for (const t of tok) if (Object.prototype.hasOwnProperty.call(w, t)) s += w[t]; return s; };

// threshold on dev only: the highest dev recall with dev false alarms at most TARGET_FA (ties: the higher threshold)
const devScored = dev.map(d => ({ s: devScore(d.tok), y: d.y }));
const devPos = devScored.filter(x => x.y === 1).length, devNeg = devScored.length - devPos;
let best = null;
for (const t of [...new Set(devScored.map(x => x.s))].sort((a, b) => a - b)) {
  const tp = devScored.filter(x => x.y === 1 && x.s >= t).length;
  const fp = devScored.filter(x => x.y === 0 && x.s >= t).length;
  if (fp / devNeg <= TARGET_FA) {
    const rec = tp / devPos;
    if (!best || rec > best.rec || (rec === best.rec && t > best.t)) best = { t, rec };
  }
}
if (!best) throw new Error('no dev threshold meets the false-alarm target');
const threshold = best.t;

fs.writeFileSync(OUT, '// Generated by tools/build-sms-model.js from the dev half only. Do not edit by hand.\n'
  + 'export const SMS_MODEL = ' + JSON.stringify({ prior, threshold, w }) + ';\n');
console.log(`wrote engine/smsmodel-data.js: vocabulary ${V}, threshold ${threshold}`);

// check the shipped scorer against the measured report (same counts, same threshold)
const eng = await import(pathToFileURL(path.join(ROOT, 'engine', 'smsmodel.js')).href);
const report = JSON.parse(fs.readFileSync(REPORT, 'utf8'));
const c = { tp: 0, fn: 0, fp: 0, tn: 0 };
for (const x of testRaw) {
  const flag = eng.smsLocal(x.text).flag;
  if (x.y === 1) { if (flag) c.tp++; else c.fn++; }
  else if (flag) c.fp++; else c.tn++;
}
const same = report.dev.threshold === threshold && report.test.tp === c.tp && report.test.fn === c.fn && report.test.fp === c.fp && report.test.tn === c.tn;
console.log(`shipped scorer on the test half: tp ${c.tp}, fn ${c.fn}, fp ${c.fp}, tn ${c.tn}; report: tp ${report.test.tp}, fn ${report.test.fn}, fp ${report.test.fp}, tn ${report.test.tn}`);
console.log(same ? 'MATCH: the shipped scorer reproduces the measured result' : 'MISMATCH: the shipped scorer does not reproduce the measured result');
if (!same) process.exit(1);
